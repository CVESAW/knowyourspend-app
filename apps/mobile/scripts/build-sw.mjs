// Writes dist/sw.js after `expo export`: precaches the app shell (HTML, JS bundles, icons) under a
// version derived from the bundle hashes, so a new deploy replaces the old cache. The OCR and PDF
// engines are cached the first time they're used. User data is never cached — it lives in IndexedDB.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";
const require = createRequire(import.meta.url);
const engineVersion = ["tesseract.js", "pdfjs-dist", "@tesseract.js-data/eng"].map((p) => { try { return require(p + "/package.json").version; } catch { return "0"; } }).join("_");

const dist = join(process.cwd(), "dist");
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(dist)
  .map((f) => "/" + relative(dist, f).split("\\").join("/"))
  .filter((f) => !f.startsWith("/ocr/") && !f.startsWith("/pdf/") && !f.startsWith("/data/") && f !== "/sw.js" && !f.endsWith(".map") && f !== "/metadata.json");
const shell = ["/", ...files.filter((f) => f !== "/index.html")];
const version = createHash("sha256").update(files.map((f) => f + statSync(join(dist, f)).size).join("|")).update(readFileSync(join(dist, "index.html"))).digest("hex").slice(0, 12);

const sw = `/* KnowYourSpend service worker — generated by scripts/build-sw.mjs. Caches the app, never your data. */
const VERSION = ${JSON.stringify(version)};
const SHELL = "kys-shell-" + VERSION;
const ENGINES = "kys-engines-${engineVersion}";
const PRECACHE = ${JSON.stringify(shell)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => (k.startsWith("kys-shell-") && k !== SHELL) || (k.startsWith("kys-engines-") && k !== ENGINES)).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  // Page loads: network first (to pick up new versions), fall back to the cached app offline.
  if (req.mode === "navigate") {
    e.respondWith(fetch(req).catch(() => caches.match("/", { cacheName: SHELL })));
    return;
  }
  // Receipt reader and PDF reader: cache on first use (they're large and versioned with the app).
  if (url.pathname.startsWith("/ocr/") || url.pathname.startsWith("/pdf/")) {
    e.respondWith(
      caches.open(ENGINES).then((c) =>
        c.match(req).then((hit) => hit || fetch(req).then((res) => (res.ok && c.put(req, res.clone()), res))),
      ),
    );
    return;
  }
  // The brand list (fetched after first paint, named by content hash): cache on first use with the app.
  if (url.pathname.startsWith("/data/")) {
    e.respondWith(
      caches.open(SHELL).then((c) =>
        c.match(req).then((hit) => hit || fetch(req).then((res) => (res.ok && c.put(req, res.clone()), res))),
      ),
    );
    return;
  }
  // App files: cache first.
  e.respondWith(caches.match(req, { cacheName: SHELL }).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(dist, "sw.js"), sw);
console.log(`[build-sw] dist/sw.js: ${shell.length} files, version ${version}`);
