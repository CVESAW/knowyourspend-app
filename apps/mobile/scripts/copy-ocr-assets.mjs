// Copies Tesseract.js (script, worker, WASM core) and English language data into public/ocr so that
// receipt reading makes NO third-party network requests (by default Tesseract.js fetches these from a
// CDN — which would break the "stays on your phone" promise).
import { cpSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
const require = createRequire(import.meta.url);
const out = join(process.cwd(), "public", "ocr");
mkdirSync(out, { recursive: true });
try {
  const tjs = dirname(require.resolve("tesseract.js/package.json"));
  cpSync(join(tjs, "dist", "tesseract.min.js"), join(out, "tesseract.min.js"));
  cpSync(join(tjs, "dist", "worker.min.js"), join(out, "worker.min.js"));
  const core = dirname(require.resolve("tesseract.js-core/package.json", { paths: [tjs] }));
  for (const f of readdirSync(core)) {
    if (/^tesseract-core.*lstm.*\.(js|wasm)$/.test(f)) cpSync(join(core, f), join(out, f));
  }
  const eng = dirname(require.resolve("@tesseract.js-data/eng/package.json"));
  const candidates = ["4.0.0_best_int/eng.traineddata.gz", "4.0.0/eng.traineddata.gz", "eng.traineddata.gz"];
  const found = candidates.map((c) => join(eng, c)).find((p) => existsSync(p));
  if (found) cpSync(found, join(out, "eng.traineddata.gz"));
  else console.warn("[copy-ocr-assets] eng.traineddata.gz not found in", eng);
  console.log("[copy-ocr-assets] OCR assets copied to public/ocr");
} catch (e) {
  console.warn("[copy-ocr-assets] skipped:", e.message);
}

// pdf.js (script + worker) for reading PDF statements on the device — also served from our own origin.
try {
  const pdfOut = join(process.cwd(), "public", "pdf");
  mkdirSync(pdfOut, { recursive: true });
  const pdfjs = dirname(require.resolve("pdfjs-dist/package.json"));
  for (const f of ["pdf.min.mjs", "pdf.worker.min.mjs"]) cpSync(join(pdfjs, "build", f), join(pdfOut, f));
  console.log("[copy-ocr-assets] pdf.js copied to public/pdf");
} catch (e) {
  console.warn("[copy-ocr-assets] pdf.js skipped:", e.message);
}

// pdf.js for the phone apps: the phone app reads PDFs inside a sealed, offline WebView (see
// src/lib/pdf-engine.ts). The engine's code is compiled into the app as text so nothing is fetched.
try {
  const { readFileSync, writeFileSync } = await import("node:fs");
  const pdfjs = dirname(require.resolve("pdfjs-dist/package.json"));
  const version = JSON.parse(readFileSync(join(pdfjs, "package.json"), "utf8")).version;
  const main = readFileSync(join(pdfjs, "legacy", "build", "pdf.min.mjs"), "utf8");
  const worker = readFileSync(join(pdfjs, "legacy", "build", "pdf.worker.min.mjs"), "utf8");
  const out = join(process.cwd(), "src", "lib", "pdf-engine.generated.ts");
  writeFileSync(
    out,
    `// Generated by scripts/copy-ocr-assets.mjs from pdfjs-dist ${version} (legacy build). Do not edit.\n` +
      `export const PDFJS_VERSION = ${JSON.stringify(version)};\n` +
      `export const PDFJS_MAIN: string = ${JSON.stringify(main)};\n` +
      `export const PDFJS_WORKER: string = ${JSON.stringify(worker)};\n`,
  );
  console.log("[copy-ocr-assets] pdf.js engine written for the phone app");
} catch (e) {
  console.warn("[copy-ocr-assets] pdf.js engine skipped:", e.message);
}
